#INNER JOIN -->IT GIVES ALL MATCHING ROWS FROM THE BOTH THE TABLES

#1. Display employee name and department name
SELECT CONCAT(E.FIRST_NAME,' ',E.LAST_NAME)AS FULL_NAME,D.DEPARTMENT_NAME
FROM EMPLOYEES E
JOIN DEPARTMENTS D
ON E.EMPLOYEE_ID=D.DEPARTMENT_ID;

#2. Display employee name, salary, and job title.
SELECT CONCAT(E.FIRST_NAME,' ',E.LAST_NAME)AS FULL_NAME,E.SALARY,J.JOB_TITLE
FROM EMPLOYEES E
INNER JOIN JOBS J
ON E.JOB_ID=J.JOB_ID;

#4. Show all employees working in the IT department
SELECT CONCAT(E.FIRST_NAME,' ',E.LAST_NAME)AS FULL_NAME,D.DEPARTMENT_NAME
FROM EMPLOYEES E
INNER JOIN DEPARTMENTS D
ON E.DEPARTMENT_ID=D.DEPARTMENT_ID
WHERE DEPARTMENT_NAME='IT';

#6. Find employees whose salary is greater than 10000 along with their department name
SELECT CONCAT(E.FIRST_NAME,' ',E.LAST_NAME)AS FULL_NAME,E.SALARY,D.DEPARTMENT_NAME
FROM EMPLOYEES E
INNER JOIN DEPARTMENTS D
ON E.DEPARTMENT_ID=D.DEPARTMENT_ID
 WHERE SALARY>10000;
 
 
 # Show employees working in cities located in the United States
 SELECT CONCAT(E.FIRST_NAME,' ',E.LAST_NAME)AS EMP_NAME,D.DEPARTMENT_NAME,L.CITY,C.COUNTRY_NAME
FROM EMPLOYEES E 
INNER JOIN DEPARTMENTS D
ON E.DEPARTMENT_ID=D.DEPARTMENT_ID
INNER JOIN LOCATIONS L
ON D.LOCATION_ID=L.LOCATION_ID
INNER JOIN COUNTRIES C
ON L.COUNTRY_ID=C.COUNTRY_ID 
WHERE COUNTRY_NAME='UNITED STATES OF AMERICA';


#Display department name and the number of employees in each department
SELECT D.DEPARTMENT_NAME,COUNT(E.EMPLOYEE_ID)AS EMP_COUNT
FROM EMPLOYEES E
INNER JOIN DEPARTMENTS D
ON E.DEPARTMENT_ID=D.DEPARTMENT_ID
GROUP BY D.DEPARTMENT_NAME;


#LEFT JOIN Practice Questions
#11. Display all departments and their employees.     #TO DISPLAY ALL THE DEPARTMENTS WE SHOULD MENTION DEPARTMENT ON LEFT SIDE
SELECT D.DEPARTMENT_NAME,COUNT(E.EMPLOYEE_ID)AS EMP_COUNT
FROM DEPARTMENTS D
LEFT JOIN EMPLOYEES E
ON E.DEPARTMENT_ID=D.DEPARTMENT_ID
GROUP BY D.DEPARTMENT_NAME;

#12. Find departments that have no employees
SELECT D.DEPARTMENT_NAME,COUNT(E.EMPLOYEE_ID)AS EMP_COUNT
FROM DEPARTMENTS D
LEFT JOIN EMPLOYEES E
ON E.DEPARTMENT_ID=D.DEPARTMENT_ID
GROUP BY D.DEPARTMENT_NAME
HAVING EMP_COUNT=0;

