#26. Display employee name and manager name
#(SELF JOIN)
SELECT CONCAT(E.FIRST_NAME,E.LAST_NAME)AS EMP_NAME,
       CONCAT(M.FIRST_NAME,M.LAST_NAME)AS MANAGR_NAME
FROM EMPLOYEES E
INNER JOIN EMPLOYEES m
ON E.MANAGER_ID=M.EMPLOYEE_ID;

#. Find employees earning more than their manager
SELECT CONCAT(E.FIRST_NAME,E.LAST_NAME)AS EMP_NAME,
       CONCAT(M.FIRST_NAME,M.LAST_NAME)AS MANAGR_NAME,
       E.SALARY,M.SALARY
FROM EMPLOYEES E
INNER JOIN EMPLOYEES m
ON E.MANAGER_ID=M.EMPLOYEE_ID
WHERE E.SALARY>M.SALARY;

#Find managers who supervise more than 5 employees.

SELECT MANAGER_ID,
       COUNT(*) AS EMP_COUNT
FROM EMPLOYEES
GROUP BY MANAGER_ID
HAVING COUNT(*) > 5;
