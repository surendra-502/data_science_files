#1. Find the top 5 highest-paid employees
SELECT EMPLOYEE_ID,CONCAT(FIRST_NAME,' ',LAST_NAME)AS EMPLOYEE_NAME ,SALARY
FROM EMPLOYEES
ORDER BY SALARY DESC,EMPLOYEE_ID
LIMIT 5;

#2. Find employees with the 6th to 10th highest salaries.
SELECT DISTINCT SALARY
FROM EMPLOYEES
ORDER BY SALARY DESC
LIMIT 5,5;
#THIS APPROACH ONLY GIVE THE SALARY ONLY IF WE NEED THE EMPLOYEE NAMES WE NEED TO USE DENSE RANK
SELECT *
FROM(
SELECT EMPLOYEE_ID,
CONCAT(FIRST_NAME,' ',LAST_NAME)AS EMPLOYEE_NAME,
SALARY,
DENSE_RANK() OVER(ORDER BY SALARY DESC) AS SALARY_RANK
FROM EMPLOYEES
)T
WHERE SALARY_RANK BETWEEN 6 AND 10;


