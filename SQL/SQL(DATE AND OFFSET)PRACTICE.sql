#ind the year in which the maximum number of employees joined.
SELECT COUNT(EMPLOYEE_ID)AS EMPLOYEE_COUNT,YEAR(HIRE_DATE) AS JOINING_YEAR
FROM EMPLOYEES
GROUP BY JOINING_YEAR
ORDER BY EMPLOYEE_COUNT DESC
LIMIT 5;

#Find the month with the highest employee joining count.
SELECT COUNT(EMPLOYEE_ID)AS EMPLOYEE_COUNT,MONTHNAME(HIRE_DATE) AS JOINING_MONTH
FROM EMPLOYEES
GROUP BY JOINING_MONTH
ORDER BY EMPLOYEE_COUNT DESC
LIMIT 5;

#. Find departments where employee count is between 3 and 10
SELECT DEPARTMENT_ID,COUNT(EMPLOYEE_ID)AS EMP_COUNT
FROM EMPLOYEES
GROUP BY DEPARTMENT_ID
HAVING COUNT(EMPLOYEE_ID) BETWEEN 3 AND 10
ORDER BY EMP_COUNT DESC ;

#Find employees whose experience is between 15 and 25 years.
SELECT FIRST_NAME,ROUND(DATEDIFF(CURRENT_DATE(),HIRE_DATE)/365) AS EXPRIENCE
FROM EMPLOYEES
WHERE ROUND(DATEDIFF(CURRENT_DATE(),HIRE_DATE)/365) BETWEEN 25 AND 30;

#Find the top 3 experienced employees.
SELECT *
FROM(
SELECT 
CONCAT(FIRST_NAME,' ',LAST_NAME)AS EMPLOYEE_NAME,
ROUND(DATEDIFF(CURRENT_DATE(),HIRE_DATE)/365) AS EXPRIENCE,
ROW_NUMBER() OVER(ORDER BY ROUND(DATEDIFF(CURRENT_DATE(),HIRE_DATE)/365) DESC)AS ROW_RANK
FROM EMPLOYEES
)T
WHERE ROW_RANK <=3;

