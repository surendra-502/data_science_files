#DATEDIFF Practice
#11. Find the experience of every employee in years.
SELECT CONCAT(FIRST_NAME,' ',LAST_NAME)AS EMPLOYEE_NAME,ROUND(DATEDIFF(CURRENT_DATE(),HIRE_DATE)/365) AS EXPRIENCE
FROM EMPLOYEES;

#12. Find employees having more than 20 years of experience.
SELECT CONCAT(FIRST_NAME,' ',LAST_NAME)AS EMPLOYEE_NAME,ROUND(DATEDIFF(CURRENT_DATE(),HIRE_DATE)/365) AS EXPRIENCE
FROM EMPLOYEES
WHERE ROUND(DATEDIFF(CURRENT_DATE(),HIRE_DATE)/365)>20;

#14. Count employees with experience greater than 15 years
SELECT COUNT(*) AS EMPLOYEE_COUNT
FROM EMPLOYEES
