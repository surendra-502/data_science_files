#JOINS TYPES
#INNER JOIN--->THIS JOIN WILL RETRIVE ALL THE COMMON ELEMENTS FROM  BOTH THE TABLE
#LEFT JOIN
SELECT CONCAT(E.FIRST_NAME,E.LAST_NAME) AS FULL_NAME,E.EMAIL,E.SALARY,E.DEPARTMENT_ID,D.DEPARTMENT_NAME
FROM EMPLOYEES E 
LEFT JOIN DEPARTMENTS D
ON E.DEPARTMENT_ID=D.DEPARTMENT_ID
WHERE E.DEPARTMENT_ID IS NULL;


#RIGHT JOIN
SELECT CONCAT(E.FIRST_NAME,E.LAST_NAME) AS FULL_NAME,E.EMAIL,E.SALARY,D.DEPARTMENT_ID,D.DEPARTMENT_NAME
FROM EMPLOYEES E 
RIGHT JOIN DEPARTMENTS D
ON E.DEPARTMENT_ID=D.DEPARTMENT_ID
WHERE E.DEPARTMENT_ID IS NULL;

