#Calculate the running total of salaries ordered by hire date using a window function.
SELECT EMPLOYEE_ID,HIRE_DATE,SALARY,
SUM(SALARY)OVER(ORDER BY HIRE_DATE ASC)AS RUNNING_TOTAL
FROM EMPLOYEES
