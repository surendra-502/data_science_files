#List all employees with a salary greater than 10,000, sorted by salary descending
SELECT EMPLOYEE_ID,CONCAT(FIRST_NAME,' ',LAST_NAME)AS EMP_NAME,SALARY
FROM EMPLOYEES
WHERE SALARY>10000
ORDER BY SALARY DESC;

#Find all employees whose last name starts with "S".
SELECT EMPLOYEE_ID,FIRST_NAME,LAST_NAME
FROM EMPLOYEES
WHERE LAST_NAME LIKE 'S%';

#Get the names and hire dates of employees hired between 2005 and 2007.
SELECT CONCAT(FIRST_NAME,LAST_NAME)AS EMP_NAME,HIRE_DATE
FROM EMPLOYEES
WHERE YEAR(HIRE_DATE) BETWEEN 1990 AND 2000;

#List employees who don't have a manager (manager_id is NULL)
SELECT EMPLOYEE_ID,FIRST_NAME
FROM EMPLOYEES 
WHERE MANAGER_ID IS NULL;

#Find all employees earning a commission (commission_pct is not NULL).
SELECT EMPLOYEE_ID,FIRST_NAME,COMMISSION_PCT
FROM EMPLOYEES
WHERE COMMISSION_PCT IS NOT NULL;

#6. Find the average salary for each department
SELECT AVG(SALARY),DEPARTMENT_ID
FROM EMPLOYEES
GROUP BY DEPARTMENT_ID;

#Count the number of employees in each job role
SELECT JOB_ID,COUNT(*)AS EMP_COUNT
FROM EMPLOYEES
GROUP BY JOB_ID;

#8. Find departments that have more than 5 employees
SELECT DEPARTMENT_ID,COUNT(*) AS EMP_COUNT
FROM EMPLOYEES
GROUP BY DEPARTMENT_ID
HAVING COUNT(*)>5;

#9. Find the highest and lowest salary in each department.
SELECT DEPARTMENT_ID,MAX(SALARY)AS MAX_SALARY,MIN(SALARY)AS MIN_SALARY
FROM EMPLOYEES
GROUP BY DEPARTMENT_ID;

#10. List job titles where the average salary exceeds 8,000
SELECT JOB_ID,AVG(SALARY) AS AVG_SALARY
FROM EMPLOYEES
GROUP BY JOB_ID
HAVING AVG_SALARY >8000;

#11. List each employee's name along with their department name
SELECT E.EMPLOYEE_ID,CONCAT(E.FIRST_NAME,' ' ,E.LAST_NAME) AS EMP_NAME, D.DEPARTMENT_NAME
FROM EMPLOYEES E
JOIN DEPARTMENTS D
ON E.DEPARTMENT_ID=D.DEPARTMENT_ID;

#Find employees who work in the "IT" department, showing employee name and job title.
SELECT E.EMPLOYEE_ID,CONCAT(E.FIRST_NAME,' ' ,E.LAST_NAME) AS EMP_NAME, D.DEPARTMENT_NAME,J.JOB_TITLE
FROM EMPLOYEES E
JOIN DEPARTMENTS D ON E.DEPARTMENT_ID=D.DEPARTMENT_ID
JOIN JOBS J ON E.JOB_ID=J.JOB_ID
WHERE D.DEPARTMENT_NAME='IT';

#13. List all departments along with their manager's name (self-referencing join hint: manager_id maps to employee_id)
SELECT D.DEPARTMENT_NAME, CONCAT(M.FIRST_NAME, ' ', M.LAST_NAME) AS MANAGER_NAME
FROM DEPARTMENTS D
LEFT JOIN EMPLOYEES M ON D.MANAGER_ID = M.EMPLOYEE_ID;

#14. Find employees who have changed departments at least once (use JOB_HISTORY).
SELECT EMPLOYEE_ID
FROM (
    SELECT EMPLOYEE_ID, DEPARTMENT_ID FROM JOB_HISTORY
    UNION
    SELECT EMPLOYEE_ID, DEPARTMENT_ID FROM EMPLOYEES
) AS combined
GROUP BY EMPLOYEE_ID
HAVING COUNT(DISTINCT DEPARTMENT_ID) > 1;

#16. Find employees who earn more than the average salary of their own department
SELECT EMPLOYEE_ID,FIRST_NAME,DEPARTMENT_ID,SALARY
FROM EMPLOYEES E
WHERE SALARY>
(  
    SELECT AVG(SALARY) 
    FROM EMPLOYEES
    WHERE DEPARTMENT_ID=E.DEPARTMENT_ID
    );

#Find the second-highest salary in the company (without using LIMIT/TOP).
SELECT*
FROM
(SELECT EMPLOYEE_ID,FIRST_NAME,SALARY,
DENSE_RANK()OVER(ORDER BY SALARY DESC) AS RNK
FROM EMPLOYEES)T
WHERE RNK=2;

#18. Rank employees within each department by salary using
SELECT EMPLOYEE_ID,FIRST_NAME,DEPARTMENT_ID,SALARY,
DENSE_RANK()OVER(PARTITION BY DEPARTMENT_ID ORDER BY SALARY DESC)AS RNK
FROM EMPLOYEES;

#19. Find each department's top 2 highest-paid employees
SELECT*
FROM(
SELECT EMPLOYEE_ID,DEPARTMENT_ID,SALARY,
ROW_NUMBER()OVER(PARTITION BY DEPARTMENT_ID ORDER BY SALARY DESC) AS RNK
FROM EMPLOYEES
