#Find departments where the difference between maximum and minimum salary is greater than 10000
USE HR;
SELECT * FROM EMPLOYEES;
SELECT DEPARTMENT_ID,MAX(SALARY)-MIN(SALARY) AS SALARY_DIFF
FROM EMPLOYEES
GROUP BY DEPARTMENT_ID
HAVING MAX(SALARY)-MIN(SALARY)>5000;

#Find job roles where the highest salary is at least twice the lowest salary.
SELECT JOB_ID,MIN(SALARY)*2 AS TWICE_LOWSALARY
FROM EMPLOYEES
GROUP BY JOB_ID
HAVING MAX(SALARY)>=TWICE_LOWSALARY;
#OR
SELECT JOB_ID,
       MIN(SALARY) AS LOWEST_SALARY,
       MAX(SALARY) AS HIGHEST_SALARY
FROM EMPLOYEES
GROUP BY JOB_ID
HAVING MAX(SALARY) >= 2 * MIN(SALARY);

#Find the second highest-paid department based on total salary
SELECT DEPARTMENT_ID,SUM(SALARY) AS TOTAL_SALARY
FROM EMPLOYEES
GROUP BY DEPARTMENT_ID
ORDER BY TOTAL_SALARY DESC
LIMIT 1,1;

#Find the top 3 managers by team salary.
SELECT MANAGER_ID,SUM(SALARY) AS TOTAL_SALARY
FROM EMPLOYEES
GROUP BY MANAGER_ID
ORDER BY TOTAL_SALARY DESC
LIMIT 3;

#Find departments where employee count is above average and average salary is also above average
SELECT DEPARTMENT_ID ,COUNT(EMPLOYEE_ID)AS EMP_COUNT,AVG(SALARY) AS AVG_SALARY
FROM EMPLOYEES
GROUP BY DEPARTMENT_ID
HAVING EMP_COUNT>
( 
SELECT AVG(EMP_COUNT)
FROM(
SELECT COUNT(*) AS EMP_COUNT
FROM EMPLOYEES
GROUP BY DEPARTMENT_ID
)T
)
AND AVG(SALARY)>
(
SELECT AVG(SALARY) FROM EMPLOYEES
);

#Find job roles whose total salary exceeds the average total salary of all job roles.
SELECT JOB_ID,SUM(SALARY)AS TOTAL_SALARY
FROM EMPLOYEES
GROUP BY JOB_ID
HAVING TOTAL_SALARY> 
(SELECT AVG(TOTAL_SALARY)
FROM
(
   SELECT SUM(SALARY) AS TOTAL_SALARY
   FROM EMPLOYEES
   GROUP BY JOB_ID
   )T
);

#Find the department with the maximum average salary among departments having at least 5 employees
SELECT DEPARTMENT_ID,MAX(SALARY),COUNT(EMPLOYEE_ID)AS EMP_COUNT
FROM EMPLOYEES
GROUP BY DEPARTMENT_ID
HAVING COUNT(*) >=5;

#Find duplicate records in a table.
SELECT FIRST_NAME,DEPARTMENT_ID,COUNT(*) AS DUPLICATE_COUNT
FROM EMPLOYEES
GROUP BY FIRST_NAME,DEPARTMENT_ID
HAVING COUNT(*)>1;

#Rank employees based on salary
SELECT EMPLOYEE_ID,FIRST_NAME,LAST_NAME,SALARY,
DENSE_RANK()  OVER(ORDER BY SALARY DESC)AS RANK_ROW
FROM EMPLOYEES;

SELECT *,
ROW_NUMBER()OVER(ORDER BY SALARY DESC)AS  ROWNUMBER
FROM EMPLOYEES;

SELECT CONCAT(FIRST_NAME,LAST_NAME)AS EMP_NAME,SALARY,DEPARTMENT_ID,
NTILE(2)  OVER(ORDER BY SALARY DESC)AS ROW_VALUE
 FROM EMPLOYEES;
 
#Find the top 3 salaries.
SELECT*
FROM(
   SELECT
   CONCAT(FIRST_NAME,LAST_NAME)AS EMP_NAME,SALARY,
    row_number()OVER(ORDER BY SALARY DESC) AS ROW_RANK
     FROM EMPLOYEES
)T
WHERE ROW_RANK<=3;

